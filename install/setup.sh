#!/usr/bin/env bash
#
# setup.sh: turn a fresh arch-install.sh system into the full desktop from this repo.
# Run as your normal user (not root) after the first boot; it asks for sudo when needed.
# Every step is safe to run again.
#
# Usage:
#   bash install/setup.sh                # all steps
#   bash install/setup.sh --dry-run      # print what would run, change nothing
#   bash install/setup.sh dotfiles theme # only some steps (names listed in --help)
#
# Environment:
#   SETUP_HOST   folder under hosts/ with machine-specific packages and /etc files
#                (default: tuf-f16; set to "none" for a machine without one)

if [ -z "${BASH_VERSION:-}" ]; then
  echo "Run this script with bash: bash install/setup.sh" >&2
  exit 1
fi

set -Eeuo pipefail

REPO=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)
readonly REPO
readonly HOST=${SETUP_HOST:-tuf-f16}
readonly ALL_STEPS=(mirrors packages aur dotfiles system services greeter snapper hibernate distrobox plugins theme)

readonly BOLD=$'\e[1m' RED=$'\e[31m' GREEN=$'\e[32m' YELLOW=$'\e[33m' RESET=$'\e[0m'
DRY_RUN=0

info() { printf '%s\n' "${GREEN}::${RESET} $*"; }
warn() { printf '%s\n' "${YELLOW}!! $*${RESET}"; }
die() {
  printf '%s\n' "${RED}xx $*${RESET}" >&2
  exit 1
}
step() { printf '\n%s\n' "${BOLD}==> $*${RESET}"; }
trap 'printf "%s\n" "${RED}xx Failed at line ${LINENO}: ${BASH_COMMAND}${RESET}" >&2' ERR

# run CMD...: run it, or only print it in dry-run mode
run() {
  if ((DRY_RUN)); then
    printf '  '
    printf ' %q' "$@"
    printf '\n'
  else
    "$@"
  fi
}

# package names from one or more lists, comments and blank lines removed
pkgs_from() { sed -e 's/#.*//' -e '/^[[:space:]]*$/d' "$@"; }

usage() {
  cat <<EOF
Usage: bash install/setup.sh [--dry-run] [step...]

Steps (default: all, in this order):
  mirrors   rank nearby pacman mirrors by real download speed (install/rank-mirrors.sh)
  packages  official packages from packages/*.txt (full system upgrade first)
  aur       bootstrap yay, then AUR packages from packages/aur.txt
  dotfiles  link config/* into \$HOME with GNU Stow (existing files are backed up),
            and extras/firefox/user.js into each Firefox profile
  system    copy system/etc and hosts/\$SETUP_HOST/etc into /etc, rebuild initramfs
  services  enable system services (network, bluetooth, power, zram)
  greeter   boot login screen: greetd + the Quickshell greeter (extras/greeter), replaces sddm
  snapper   snapper config for /, timeline snapshots, snapshot entries in GRUB
  hibernate swapfile (size of RAM) on its own Btrfs subvolume @swap, for hibernation
  distrobox an Ubuntu container (\$DISTROBOX_IMAGE) for Ubuntu-only apps, with podman
  plugins   build and enable the hyprbars plugin with hyprpm (inside Hyprland only)
  theme     GTK/icon/cursor theme and fonts (inside a graphical session only)

Host: ${HOST} (set SETUP_HOST to change)
EOF
}

# ---------------------------------------------------------------- steps

step_mirrors() {
  step "Pacman mirrors"
  # Skip when rank-mirrors.sh wrote the list in the last 7 days (its header carries the
  # date). To re-rank anyway: bash install/rank-mirrors.sh
  local made age_days
  made=$(sed -n 's/^# Generated by install\/rank-mirrors\.sh on \([0-9-]*\)$/\1/p' /etc/pacman.d/mirrorlist 2>/dev/null | head -1)
  if [[ -n $made ]]; then
    age_days=$((($(date +%s) - $(date -d "$made" +%s)) / 86400))
    if ((age_days < 7)); then
      info "Mirrors ranked on $made ($age_days days ago); skipping. Re-rank: bash install/rank-mirrors.sh"
      return 0
    fi
  fi
  if ((DRY_RUN)); then
    run bash "$REPO/install/rank-mirrors.sh"
  else
    bash "$REPO/install/rank-mirrors.sh"
  fi
}

step_packages() {
  step "Official packages"
  local lists=("$REPO"/packages/base.txt "$REPO"/packages/hyprland-desktop.txt "$REPO"/packages/apps.txt)
  [[ -f $REPO/packages/hardware-$HOST.txt ]] && lists+=("$REPO/packages/hardware-$HOST.txt")
  info "Lists: ${lists[*]#"$REPO"/}"
  mapfile -t pkgs < <(pkgs_from "${lists[@]}")
  run sudo pacman -Syu --needed "${pkgs[@]}"
}

step_aur() {
  step "AUR packages"
  if ! command -v yay >/dev/null; then
    info "Bootstrapping yay-bin from the AUR"
    local tmp
    tmp=$(mktemp -d)
    run git clone --depth 1 https://aur.archlinux.org/yay-bin.git "$tmp/yay-bin"
    if ((DRY_RUN)); then
      printf '   (cd %q && makepkg -si --noconfirm)\n' "$tmp/yay-bin"
    else
      (cd "$tmp/yay-bin" && makepkg -si --noconfirm)
    fi
    rm -rf "$tmp"
  fi
  mapfile -t pkgs < <(pkgs_from "$REPO/packages/aur.txt")
  run yay -S --needed "${pkgs[@]}"
}

step_dotfiles() {
  step "Dotfiles (GNU Stow)"
  local pkg rel target stamp
  stamp=$(date +%Y%m%d-%H%M%S)
  for pkg in "$REPO"/config/*/; do
    pkg=$(basename "$pkg")
    # A real file where Stow wants a link (e.g. the hyprland.lua Hyprland writes on first
    # start) makes Stow refuse; move it aside first.
    while IFS= read -r rel; do
      target="$HOME/$rel"
      # Already ours: the file itself or one of its parent dirs links into the repo
      [[ $(realpath -- "$target" 2>/dev/null) == "$REPO/config/$pkg/$rel" ]] && continue
      if [[ -e $target && ! -L $target && ! -d $target ]]; then
        warn "Backing up $target -> $target.bak-$stamp"
        run mv "$target" "$target.bak-$stamp"
      fi
    done < <(cd "$REPO/config/$pkg" && find . -type f -printf '%P\n')
    info "stow $pkg"
    run stow -d "$REPO/config" -t "$HOME" -R "$pkg"
  done
  # Firefox profile dirs have random names, so Stow can't place user.js; link it into each
  # existing profile (start Firefox once first so a profile exists).
  local prof
  for prof in "$HOME"/.config/mozilla/firefox/*/prefs.js "$HOME"/.mozilla/firefox/*/prefs.js; do
    [[ -e $prof ]] || continue
    prof=$(dirname "$prof")
    info "firefox user.js -> $prof"
    run ln -sfn "$REPO/extras/firefox/user.js" "$prof/user.js"
  done
}

# copy every file under SRC (a mirror of /) to the same path under /
install_tree() {
  local src=$1 rel
  [[ -d $src ]] || return 0
  while IFS= read -r rel; do
    if cmp -s "$src/$rel" "/$rel" 2>/dev/null; then
      continue
    fi
    info "/$rel"
    run sudo install -Dm644 "$src/$rel" "/$rel"
  done < <(cd "$src" && find . -type f -printf '%P\n')
}

step_system() {
  step "System files in /etc"
  install_tree "$REPO/system"
  [[ $HOST != none ]] && install_tree "$REPO/hosts/$HOST"
  run sudo udevadm control --reload
  run sudo udevadm trigger --subsystem-match=drm
  run sudo udevadm trigger --subsystem-match=input --action=change
  run sudo sysctl --system --quiet
  info "Rebuilding initramfs"
  run sudo mkinitcpio -P
}

# enable_units [--now] UNIT...: enable the units that are installed, skip the others
enable_units() {
  local now=() unit
  [[ $1 == --now ]] && now=(--now) && shift
  for unit in "$@"; do
    if systemctl list-unit-files "$unit" >/dev/null 2>&1; then
      run sudo systemctl enable "${now[@]}" "$unit"
    else
      warn "Skipping $unit (not installed)"
    fi
  done
}

step_services() {
  step "System services"
  enable_units --now NetworkManager.service bluetooth.service power-profiles-daemon.service
  # NVIDIA: keep video memory across suspend (nvidia-utils ships these, not always enabled)
  enable_units nvidia-suspend.service nvidia-resume.service nvidia-hibernate.service
  # asusd is started by udev/D-Bus; just make sure it runs now
  if systemctl list-unit-files asusd.service >/dev/null 2>&1; then
    run sudo systemctl start asusd.service || warn "asusd did not start; check: journalctl -u asusd"
  fi
  run sudo systemctl daemon-reload
  # zram-generator sets the device up at boot. Start it now only if the running kernel can
  # still load modules: a kernel upgrade in the packages step removes them until reboot.
  if [[ ! -d /usr/lib/modules/$(uname -r) ]]; then
    warn "Kernel $(uname -r) was upgraded during this run; zram starts after reboot."
  else
    run sudo systemctl start systemd-zram-setup@zram0.service ||
      warn "zram did not start now; check after reboot with: swapon --show"
  fi
}

# Boot login screen: greetd runs a small Hyprland (extras/greeter/hyprland.lua) with the
# Quickshell greeter (extras/greeter/shell.qml), the lock screen's twin. The `greeter` user
# can't read $HOME, so its files are copied into /etc/greetd/quickshell: rerun this step
# after changing the lock screen, Theme / Settings or the wallpaper. Takes effect on the
# next boot. sddm stays installed as the way back:
#   sudo systemctl disable greetd && sudo systemctl enable sddm
step_greeter() {
  step "Login screen (greetd + Quickshell greeter)"
  if ! pacman -Qq greetd >/dev/null 2>&1 && ! ((DRY_RUN)); then
    warn "greetd is not installed (packages step); login screen left as it is"
    return 0
  fi
  local qs=$REPO/config/quickshell/.config/quickshell g=$REPO/extras/greeter
  local dst=/etc/greetd/quickshell fonts=$REPO/config/fonts/.local/share/fonts f
  run sudo install -Dm644 "$g/config.toml" /etc/greetd/config.toml
  run sudo install -Dm644 "$g/hyprland.lua" /etc/greetd/hyprland.lua
  run sudo rm -rf "$dst"
  run sudo install -Dm644 "$g/shell.qml" "$dst/shell.qml"
  for f in "$qs"/config/*; do
    run sudo install -Dm644 "$f" "$dst/config/${f##*/}"
  done
  run sudo install -Dm644 "$qs/modules/lock/LockSurface.qml" "$dst/modules/lock/LockSurface.qml"
  run sudo install -Dm644 "$REPO/config/hypr/.config/hypr/wallpapers/default.png" "$dst/wallpaper.png"
  # The UI fonts (Lexend, Comfortaa) for every user, the greeter included
  while IFS= read -r f; do
    run sudo install -Dm644 "$fonts/$f" "/usr/local/share/fonts/$f"
  done < <(cd "$fonts" && find . -type f -printf '%P\n')
  run sudo fc-cache -f /usr/local/share/fonts
  if systemctl is-enabled --quiet sddm.service 2>/dev/null; then
    run sudo systemctl disable sddm.service
  fi
  enable_units greetd.service
}

# Ubuntu-only apps: a distrobox container named `ubuntu` (rootless podman). It shares $HOME,
# the Wayland display, audio and the GPU; `distrobox enter ubuntu`, then apt as usual, and
# `distrobox-export --app <name>` inside puts an app in the launcher. The image is pulled
# only the first time.
readonly DISTROBOX_NAME=ubuntu
readonly DISTROBOX_IMAGE=${DISTROBOX_IMAGE:-docker.io/library/ubuntu:24.04}
step_distrobox() {
  step "Distrobox ($DISTROBOX_NAME, $DISTROBOX_IMAGE)"
  if ! command -v distrobox >/dev/null && ! ((DRY_RUN)); then
    warn "distrobox is not installed (packages step); skipped"
    return 0
  fi
  # rootless podman maps container users onto these ranges (useradd usually adds them)
  if ! grep -q "^$USER:" /etc/subuid 2>/dev/null || ! grep -q "^$USER:" /etc/subgid 2>/dev/null; then
    run sudo usermod --add-subuids 100000-165535 --add-subgids 100000-165535 "$USER"
  fi
  if podman container exists "$DISTROBOX_NAME" 2>/dev/null; then
    info "Container $DISTROBOX_NAME already exists"
  else
    run distrobox create --yes --name "$DISTROBOX_NAME" --image "$DISTROBOX_IMAGE"
  fi
}

step_snapper() {
  step "Snapper"
  if [[ -f /etc/snapper/configs/root ]]; then
    info "snapper config 'root' already exists"
  else
    # arch-install.sh already mounts the @snapshots subvolume at /.snapshots, and
    # create-config refuses when that path exists. Unmount it, let snapper create its
    # config (it makes a nested /.snapshots subvolume), drop that nested subvolume and
    # mount @snapshots back. https://wiki.archlinux.org/title/Snapper#Configuration_of_snapper_and_mount_point
    if findmnt -n /.snapshots >/dev/null; then
      run sudo umount /.snapshots
    fi
    run sudo rmdir /.snapshots
    run sudo snapper -c root create-config /
    run sudo btrfs subvolume delete /.snapshots
    run sudo mkdir /.snapshots
    run sudo mount /.snapshots
    run sudo chmod 750 /.snapshots
  fi
  # A few hourly/daily snapshots plus the pre/post pairs snap-pac makes for every pacman run
  run sudo snapper -c root set-config \
    "ALLOW_USERS=$USER" SYNC_ACL=yes \
    TIMELINE_CREATE=yes TIMELINE_LIMIT_HOURLY=5 TIMELINE_LIMIT_DAILY=7 \
    TIMELINE_LIMIT_WEEKLY=0 TIMELINE_LIMIT_MONTHLY=0 TIMELINE_LIMIT_YEARLY=0 \
    NUMBER_LIMIT=20 NUMBER_LIMIT_IMPORTANT=10
  enable_units --now snapper-timeline.timer snapper-cleanup.timer grub-btrfsd.service
  run sudo grub-mkconfig -o /boot/grub/grub.cfg
}

# Hibernation needs swap on disk (zram lives in RAM). A swapfile on its own Btrfs
# subvolume @swap, mounted at /swap, so snapper never snapshots it; as big as RAM; low
# priority, so zram is still used first. With a systemd initramfs on UEFI no resume= /
# resume_offset= is needed: systemd stores the location in an EFI variable when hibernating.
step_hibernate() {
  step "Hibernation swapfile"
  local dev uuid size mnt
  if swapon --show=NAME --noheadings | grep -qx /swap/swapfile; then
    info "/swap/swapfile already in use"
    return
  fi
  dev=$(findmnt -no SOURCE / | sed 's/\[.*//')
  uuid=$(findmnt -no UUID /)
  # @swap exists once /swap is in fstab (checking the subvolume list needs root)
  if ! grep -q '[[:space:]]/swap[[:space:]]' /etc/fstab; then
    mnt=$(mktemp -d)
    run sudo mount -o subvolid=5 "$dev" "$mnt"
    run sudo btrfs subvolume create "$mnt/@swap"
    run sudo umount "$mnt"
    rmdir "$mnt"
  fi
  run sudo mkdir -p /swap
  if ! grep -q '[[:space:]]/swap[[:space:]]' /etc/fstab; then
    run sudo sh -c "printf 'UUID=%s\t/swap\tbtrfs\trw,noatime,ssd,space_cache=v2,subvol=/@swap\t0 0\n' '$uuid' >> /etc/fstab"
  fi
  findmnt -n /swap >/dev/null || run sudo mount /swap
  size=$(awk '/MemTotal/ { printf "%d", ($2 + 1048575) / 1048576 }' /proc/meminfo)
  [[ -f /swap/swapfile ]] || run sudo btrfs filesystem mkswapfile --size "${size}g" --uuid clear /swap/swapfile
  if ! grep -q '^/swap/swapfile' /etc/fstab; then
    run sudo sh -c "printf '/swap/swapfile\tnone\tswap\tdefaults,pri=0\t0 0\n' >> /etc/fstab"
  fi
  run sudo swapon /swap/swapfile
}

step_plugins() {
  step "Hyprland plugins (hyprpm)"
  if [[ -z ${HYPRLAND_INSTANCE_SIGNATURE:-} ]]; then
    warn "Not inside Hyprland. Log in to Hyprland and run: bash install/setup.sh plugins"
    return 0
  fi
  # Plugins are built against the installed Hyprland; rerun `hyprpm update` after every
  # Hyprland upgrade (window title bars disappear until you do).
  run hyprpm update
  if ! hyprpm list 2>/dev/null | grep -q 'hyprland-plugins'; then
    run hyprpm add https://github.com/hyprwm/hyprland-plugins
  fi
  run hyprpm enable hyprbars
  run hyprpm reload
}

# GTK3 theme in the desktop's green: the AUR whitesur-gtk-theme only ships WhiteSur's blue,
# so the green variant is built from upstream (pinned tag) into ~/.themes. GTK4 apps take
# their accent from gsettings instead (apply-theme.sh). Delete ~/.themes/WhiteSur-Dark-green
# to rebuild (after bumping the tag).
readonly WHITESUR_TAG=2026-09-10
build_whitesur_green() {
  if [[ -d $HOME/.themes/WhiteSur-Dark-green ]]; then
    info "WhiteSur-Dark-green already built"
    return 0
  fi
  local src=${XDG_CACHE_HOME:-$HOME/.cache}/whitesur-gtk-theme
  run rm -rf "$src"
  run git clone --quiet --depth 1 --branch "$WHITESUR_TAG" \
    https://github.com/vinceliuice/WhiteSur-gtk-theme.git "$src"
  run "$src/install.sh" --dest "$HOME/.themes" --color dark --theme green
  run rm -rf "$src"
}

step_theme() {
  step "Theme"
  if [[ -z ${WAYLAND_DISPLAY:-} ]]; then
    warn "No graphical session. Log in and run: bash install/setup.sh theme"
    return 0
  fi
  build_whitesur_green
  run bash "$REPO/install/apply-theme.sh"
}

# ---------------------------------------------------------------- main

main() {
  local steps=() s
  while (($#)); do
    case $1 in
      -n | --dry-run) DRY_RUN=1 ;;
      -h | --help)
        usage
        exit 0
        ;;
      -*) die "Unknown option: $1 (see --help)" ;;
      *)
        [[ " ${ALL_STEPS[*]} " == *" $1 "* ]] || die "Unknown step: $1 (see --help)"
        steps+=("$1")
        ;;
    esac
    shift
  done
  ((${#steps[@]})) || steps=("${ALL_STEPS[@]}")

  [[ $EUID -ne 0 ]] || die "Run as your normal user, not root. The script uses sudo itself."
  [[ $HOST == none || -d $REPO/hosts/$HOST ]] || die "No such host folder: hosts/$HOST"
  ((DRY_RUN)) && warn "DRY RUN: commands are printed, not run."
  info "Repo: $REPO   Host: $HOST   Steps: ${steps[*]}"

  for s in "${steps[@]}"; do
    "step_$s"
  done

  printf '\n%s\n' "${GREEN}Done.${RESET} Reboot if the NVIDIA driver, initramfs or services changed."
  [[ -d /usr/lib/modules/$(uname -r) ]] || warn "The running kernel was replaced by an upgrade: reboot now."
}

main "$@"
