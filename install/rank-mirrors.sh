#!/usr/bin/env bash
#
# rank-mirrors.sh: write /etc/pacman.d/mirrorlist with the fastest nearby mirrors.
#
# Ranks by downloading part of a real ~100 MB package from each mirror. reflector's
# "--sort rate" only fetches a small database file, which CDNs and some local mirrors
# serve fast from cache even when they crawl on real packages (measured 2026-11-19 from
# Vietnam: fastly.mirror.pkgbuild.com 11 KiB/s, mirror.xtom.com.hk 15 MB/s).
#
# Usage:
#   bash install/rank-mirrors.sh            # test, then write the mirrorlist (asks for sudo)
#   bash install/rank-mirrors.sh --dry-run  # test and print the result only
#
# Environment:
#   MIRROR_COUNTRIES  country codes to test (default: VN,SG,HK,JP,TW,KR)
#   MIRROR_KEEP       how many mirrors to keep (default: 8)
#   MIRROR_SECONDS    seconds of download per mirror (default: 5)

set -Eeuo pipefail

readonly COUNTRIES=${MIRROR_COUNTRIES:-VN,SG,HK,JP,TW,KR}
readonly KEEP=${MIRROR_KEEP:-8}
readonly SECS=${MIRROR_SECONDS:-5}
readonly OUT=/etc/pacman.d/mirrorlist
readonly STATUS_URL=https://archlinux.org/mirrors/status/json/
readonly TEST_PKG=linux-firmware-nvidia

DRY_RUN=0
case ${1:-} in
  -n | --dry-run) DRY_RUN=1 ;;
  -h | --help)
    sed -n '3,17p' "$0" | sed 's/^# \{0,1\}//'
    exit 0
    ;;
  '') ;;
  *)
    echo "Unknown option: $1 (see --help)" >&2
    exit 1
    ;;
esac

# Path of the test package relative to a mirror root, e.g. core/os/x86_64/<file>.
# Repo and file name come from the local sync database; no root needed.
read -r repo file < <(pacman -Sp --print-format '%r %f' "$TEST_PKG" 2>/dev/null) || true
[[ -n ${file:-} ]] || {
  echo "Could not resolve $TEST_PKG; run 'sudo pacman -Sy' once and retry." >&2
  exit 1
}
rel="$repo/os/x86_64/$file"

# HTTPS mirrors in those countries, fully synced within the last 24 hours
mapfile -t mirrors < <(curl -fsS --max-time 20 "$STATUS_URL" | python3 -I -c '
import json, sys
from datetime import datetime, timedelta, timezone
want = set(sys.argv[1].upper().split(","))
cutoff = datetime.now(timezone.utc) - timedelta(hours=24)
for m in json.load(sys.stdin)["urls"]:
    if m["protocol"] != "https" or not m["active"] or m["country_code"] not in want:
        continue
    if (m["completion_pct"] or 0) < 0.95 or not m["last_sync"]:
        continue
    if datetime.fromisoformat(m["last_sync"].replace("Z", "+00:00")) < cutoff:
        continue
    print(m["url"])
' "$COUNTRIES")

((${#mirrors[@]})) || {
  echo "No synced HTTPS mirrors found for $COUNTRIES." >&2
  exit 1
}
echo ":: Testing ${#mirrors[@]} mirrors in $COUNTRIES, ${SECS}s each, with $TEST_PKG"

results=()
for m in "${mirrors[@]}"; do
  # curl exits non-zero when --max-time cuts the download; the speed is still valid
  read -r code speed < <(curl -s -o /dev/null --connect-timeout 3 --max-time "$SECS" \
    -w '%{http_code} %{speed_download}\n' "$m$rel" || true)
  if [[ ${code:-000} == 200 ]]; then
    printf '   %8.2f MB/s  %s\n' "$(awk -v s="$speed" 'BEGIN{print s/1048576}')" "$m"
    results+=("${speed%.*} $m")
  else
    printf '   %8s       %s\n' "http ${code:-000}" "$m"
  fi
done

((${#results[@]})) || {
  echo "Every mirror failed; mirrorlist left unchanged." >&2
  exit 1
}

list=$(
  printf '# Generated by install/rank-mirrors.sh on %s\n' "$(date -I)"
  printf '# Countries: %s; ranked by download speed of %s\n\n' "$COUNTRIES" "$TEST_PKG"
  printf '%s\n' "${results[@]}" | sort -rn | head -n "$KEEP" | awk '{print "Server = " $2 "$repo/os/$arch"}'
)

echo
echo "$list"
if ((DRY_RUN)); then
  echo ":: Dry run: $OUT not changed."
  exit 0
fi
sudo cp -- "$OUT" "$OUT.bak"
printf '%s\n' "$list" | sudo tee "$OUT" >/dev/null
echo ":: Wrote $OUT (previous list saved as $OUT.bak)"
